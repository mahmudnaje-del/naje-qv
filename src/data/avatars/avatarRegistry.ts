export function getAvatarsByRegion(region: string): NajiAvatar[] {
  return Object.values(AVATAR_REGISTRY).filter(a => a.visualRegion.startsWith(region));
}

export function searchAvatars(query: string): NajiAvatar[] {
  const q = query.trim().toLowerCase();
  if (!q) return interleaveDiverseAvatars(Object.values(AVATAR_REGISTRY));
  return interleaveDiverseAvatars(
    Object.values(AVATAR_REGISTRY).filter(a =>
      a.name.toLowerCase().includes(q) ||
      a.visualRegion.toLowerCase().includes(q) ||
      a.profession.toLowerCase().includes(q)
    )
  );
}

/** People key: the culture after the em dash, before the parenthetical descriptor. */
export function cultureKey(avatar: NajiAvatar): string {
  const after = avatar.visualRegion.split('—')[1] || avatar.visualRegion;
  return after.split('(')[0].trim();
}

export function skinFamily(avatar: NajiAvatar): string {
  const s = avatar.skin.toLowerCase();
  if (s.includes('very deep') || s.includes('very dark')) return 'deep';
  if (s.includes('deep brown') || s.includes('dark brown')) return 'brown-deep';
  if (s.includes('warm brown') || s.includes('medium-deep') || s.includes('medium brown')) return 'brown';
  if (s.includes('tan') || s.includes('golden') || s.includes('olive') || s.includes('wheat') || s.includes('medium')) return 'medium';
  if (s.includes('light')) return 'light';
  return 'fair';
}

/** Spread peoples so the first swipe mixes continents and skin families; neighbors never share a people. */
export function interleaveDiverseAvatars(avatars: NajiAvatar[]): NajiAvatar[] {
  if (avatars.length <= 1) return avatars.slice();

  const buckets = new Map<string, NajiAvatar[]>();
  for (const av of avatars) {
    const k = cultureKey(av);
    const list = buckets.get(k);
    if (list) list.push(av);
    else buckets.set(k, [av]);
  }

  const rotation = [
    ...PEOPLE_ROTATION.filter((r) => buckets.has(r)),
    ...[...buckets.keys()].filter((k) => !PEOPLE_ROTATION.includes(k)),
  ];

  const result: NajiAvatar[] = [];
  let cursor = 0;
  while (result.length < avatars.length) {
    const last = result[result.length - 1];
    const lastC = last ? cultureKey(last) : '';
    const lastSkin = last ? skinFamily(last) : '';
    let picked: NajiAvatar | undefined;

    // Prefer different people AND different skin family.
    for (let pass = 0; pass < 2 && !picked; pass++) {
      for (let step = 0; step < rotation.length; step++) {
        const k = rotation[(cursor + step) % rotation.length];
        const list = buckets.get(k);
        if (!list?.length) continue;
        if (k === lastC) continue;
        let idx = 0;
        if (pass === 0 && lastSkin) {
          idx = list.findIndex((a) => skinFamily(a) !== lastSkin);
          if (idx < 0) continue;
        }
        picked = list.splice(idx, 1)[0];
        cursor = (cursor + step + 1) % rotation.length;
        break;
      }
    }

    if (!picked) {
      for (const k of rotation) {
        const list = buckets.get(k);
        if (list?.length) {
          picked = list.shift();
          break;
        }
      }
    }

    if (!picked) break;
    result.push(picked);
  }

  return result;
}
