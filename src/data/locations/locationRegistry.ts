export function getLocationsByCategory(category: string): NajiLocation[] {
  return Object.values(LOCATION_REGISTRY).filter(l => l.category === category);
}

export function searchLocations(query: string): NajiLocation[] {
  const q = query.trim().toLowerCase();
  if (!q) return Object.values(LOCATION_REGISTRY);
  return Object.values(LOCATION_REGISTRY).filter(l =>
    l.name.toLowerCase().includes(q) ||
    l.category.toLowerCase().includes(q) ||
    l.description.toLowerCase().includes(q)
  );
}