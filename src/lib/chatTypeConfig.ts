/**
 * Helper to get metadata for any chat type, with graceful fallback to 'text'
 */
export function getChatTypeConfig(type?: string | ChatType): ChatTypeMeta {
  if (!type) return CHAT_TYPES_CONFIG.text;
  return CHAT_TYPES_CONFIG[type] || CHAT_TYPES_CONFIG.text;
}

/**
 * Return CSS color styles for a chat type that are 100% theme-independent
 */
export function getChatTypeStyle(type?: string | ChatType) {
  const config = getChatTypeConfig(type);
  return {
    color: config.color,
    backgroundColor: config.bgTint,
    borderColor: config.borderTint
  };
}
